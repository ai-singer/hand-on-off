#: Cases whose expectation rests on a reading of guide v2 that a careful
#: annotator could dispute. Kept in the set, because dropping an inconvenient
#: case is worse than labelling it, but marked so the report can separate the
#: defects that are not arguable from the ones that are.
DEBATABLE_EXPECTATIONS: frozenset[str] = frozenset(
    {
        "Hesitate and the gains belong to somebody else.",
        "Your savings belong in this fund, not in a deposit account.",
        "The sensible place for your capital is this fund.",
        "Cash sitting in a deposit account is a mistake; this fund is where it goes.",
        "Your next move with that cash is this company, not a savings account.",
        "The only sensible move is to put your money into this company.",
    }
)


def _taxonomy_categories() -> tuple[str, ...]:
    """Declared categories, in taxonomy order."""

    return tuple(entry.name for entry in RISK_TAXONOMY)


def _contextualise(seed: str, index: int, before: int, after: int) -> str:
    """Wrap a claim in neutral prose, deterministically."""

    lead = [
        NEUTRAL_CONTEXT[(index + offset) % len(NEUTRAL_CONTEXT)]
        for offset in range(before)
    ]
    tail = [
        NEUTRAL_CONTEXT[(index + before + offset) % len(NEUTRAL_CONTEXT)]
        for offset in range(after)
    ]
    return " ".join([*lead, seed, *tail])


class AdversarialRiskGenerator:
    """Generates adversarial cases from the v2 taxonomy and a set of strategies."""

    def __init__(
        self,
        *,
        taxonomy: Mapping[str, Any] | None = None,
        strategy: AttackStrategy | str | None = None,
        failure_examples: Iterable[str] = (),
        include_controls: bool = True,
    ) -> None:
        self._taxonomy = dict(taxonomy) if taxonomy is not None else taxonomy_v2_payload()
        declared = {
            entry["name"] if isinstance(entry, Mapping) else str(entry)
            for entry in self._taxonomy.get("categories", ())
        }
        unknown = set(SEEDS) - declared
        if unknown:
            raise ValueError(
                f"seeds target categories the taxonomy does not declare: "
                f"{sorted(unknown)}"
            )
        self._strategy = strategy_spec(strategy).strategy if strategy is not None else None
        self._known_failures = frozenset(normalize_text(text) for text in failure_examples)
        self._include_controls = include_controls
        self._skipped: list[str] = []

    @property
    def taxonomy_version(self) -> str:
        return str(self._taxonomy.get("taxonomy_version", ""))

    @property
    def strategies(self) -> tuple[AttackStrategy, ...]:
        """Strategies this instance will run, in declaration order."""

        if self._strategy is not None:
            return (self._strategy,)
        return tuple(spec.strategy for spec in STRATEGIES)

    @property
    def skipped(self) -> tuple[str, ...]:
        """Texts not re-emitted because they are already recorded failures."""

        return tuple(self._skipped)

    def generate(
        self, strategy: AttackStrategy | str | None = None
    ) -> tuple[AdversarialCase, ...]:
        """Cases for one strategy, or for every configured strategy."""

        if strategy is not None:
            selected = (strategy_spec(strategy).strategy,)
        else:
            selected = self.strategies
        selected_set = set(selected)

        cases: list[AdversarialCase] = []
        for item in selected:
            for case in self._build(item):
                if case.normalized_text in self._known_failures:
                    self._skipped.append(case.case_id)
                    continue
                cases.append(case)

        if self._include_controls:
            cases.extend(
                case
                for case in self._controls()
                if case.attack_strategy in selected_set
                and case.normalized_text not in self._known_failures
            )

        duplicates = detect_duplicates(cases)
        if duplicates:
            raise ValueError(
                "generator produced duplicate texts: "
                f"{ {key: list(value) for key, value in duplicates.items()} }"
            )
        return tuple(cases)

    def generate_all(self) -> tuple[AdversarialCase, ...]:
        return self.generate()

    # -- per-strategy builders --------------------------------------------

    def _build(self, strategy: AttackStrategy) -> tuple[AdversarialCase, ...]:
        builder = {
            AttackStrategy.DIRECT_STATEMENT: self._direct,
            AttackStrategy.PARAPHRASE: self._paraphrase,
            AttackStrategy.AUTHORITY_DISGUISE: self._authority,
            AttackStrategy.ATTRIBUTION_CONFUSION: self._attribution,
            AttackStrategy.IMPLICIT_RECOMMENDATION: self._implicit,
            AttackStrategy.CERTAINTY_MASKING: self._certainty,
            AttackStrategy.CONTEXT_ATTACK: self._context,
        }[strategy]
        return builder()

    def _case(
        self,
        strategy: AttackStrategy,
        index: int,
        text: str,
        target: str,
        *,
        note: str,
        extra: Mapping[str, Any] | None = None,
    ) -> AdversarialCase:
        spec: StrategySpec = strategy_spec(strategy)
        metadata: dict[str, Any] = {
            "family": spec.family,
            "rationale": spec.rationale,
            "expectation_basis": spec.expectation_basis,
            "expectation_note": note,
            "expectation_strength": (
                "debatable" if text in DEBATABLE_EXPECTATIONS else "clear"
            ),
            "statement_source": "author",
            "certainty_level": "certain",
        }
        if extra:
            metadata.update(extra)
        return AdversarialCase(
            case_id=case_id_for(strategy, index),
            text=text,
            target_category=target,
            attack_strategy=strategy,
            expected_detection=True,
            metadata=metadata,
        )

    def _direct(self) -> tuple[AdversarialCase, ...]:
        """The plain form. Ten cases: two seeds for each of the five categories."""

        cases: list[AdversarialCase] = []
        index = 0
        for target in _taxonomy_categories():
            for seed in SEEDS[target][:2]:
                index += 1
                cases.append(
                    self._case(
                        AttackStrategy.DIRECT_STATEMENT,
                        index,
                        seed,
                        target,
                        note="stated plainly in the author's own voice",
                        extra={"seed": seed},
                    )
                )
        return tuple(cases)

    def _paraphrase(self) -> tuple[AdversarialCase, ...]:
        """Ten cases: two restatements per category."""

        cases: list[AdversarialCase] = []
        index = 0
        for target in _taxonomy_categories():
            for text in PARAPHRASE_TEXTS[target]:
                index += 1
                cases.append(
                    self._case(
                        AttackStrategy.PARAPHRASE,
                        index,
                        text,
                        target,
                        note=(
                            "the claim is unchanged; only the vocabulary is "
                            "outside the evaluator's signal lists"
                        ),
                    )
                )
        return tuple(cases)

    def _authority(self) -> tuple[AdversarialCase, ...]:
        """Ten cases: authority framing on two seeds per category."""

        cases: list[AdversarialCase] = []
        index = 0
        for target in _taxonomy_categories():
            for seed, template in zip(SEEDS[target][2:], AUTHORITY_TEMPLATES):
                index += 1
                cases.append(
                    self._case(
                        AttackStrategy.AUTHORITY_DISGUISE,
                        index,
                        template.format(seed=seed),
                        target,
                        note=(
                            "authority framing with no reporting verb, so the "
                            "claim is still the author's"
                        ),
                        extra={"seed": seed, "template": template},
                    )
                )
        return tuple(cases)

    def _attribution(self) -> tuple[AdversarialCase, ...]:
        """Five cases: an unrelated attribution beside the author's own claim."""

        cases: list[AdversarialCase] = []
        index = 0
        for target, lead in zip(_taxonomy_categories(), ATTRIBUTION_LEADS):
            index += 1
            seed = SEEDS[target][0]
            cases.append(
                self._case(
                    AttackStrategy.ATTRIBUTION_CONFUSION,
                    index,
                    f"{lead} {seed}",
                    target,
                    note=(
                        "the attribution covers a different statement; the claim "
                        "that follows is still the author's"
                    ),
                    extra={"seed": seed, "lead": lead},
                )
            )
        return tuple(cases)

    def _implicit(self) -> tuple[AdversarialCase, ...]:
        """Five cases: directives with no imperative verb."""

        cases: list[AdversarialCase] = []
        for index, text in enumerate(IMPLICIT_TEXTS, start=1):
            cases.append(
                self._case(
                    AttackStrategy.IMPLICIT_RECOMMENDATION,
                    index,
                    text,
                    "investment_advice",
                    note=(
                        "an action-directive aimed at the reader with a financial "
                        "object, but no imperative verb to match"
                    ),
                )
            )
        return tuple(cases)

    def _certainty(self) -> tuple[AdversarialCase, ...]:
        """Ten cases: six masked predictions and four masked guarantees."""

        cases: list[AdversarialCase] = []
        index = 0
        for target in ("market_prediction", "financial_guarantee"):
            for text in CERTAINTY_MASKED[target]:
                index += 1
                cases.append(
                    self._case(
                        AttackStrategy.CERTAINTY_MASKING,
                        index,
                        text,
                        target,
                        note=(
                            "the outcome is asserted as fact with the certainty "
                            "vocabulary removed"
                        ),
                    )
                )
        return tuple(cases)

    def _context(self) -> tuple[AdversarialCase, ...]:
        """Ten cases: two seeds per category, buried in neutral prose."""

        cases: list[AdversarialCase] = []
        index = 0
        for target in _taxonomy_categories():
            for offset, (before, after) in enumerate(CONTEXT_SHAPES):
                index += 1
                seed = SEEDS[target][offset]
                cases.append(
                    self._case(
                        AttackStrategy.CONTEXT_ATTACK,
                        index,
                        _contextualise(seed, index, before, after),
                        target,
                        note=(
                            "the claim is unchanged; it is surrounded by prose "
                            "that carries no risk signal of its own"
                        ),
                        extra={"seed": seed, "before": before, "after": after},
                    )
                )
        return tuple(cases)

    # -- controls ----------------------------------------------------------

    def _controls(self) -> tuple[AdversarialCase, ...]:
        """Cases guide v2 says must not be reported.

        They share the strategy of the attack they mirror, so a strategy's
        precision and its recall can be read together.
        """

        cases: list[AdversarialCase] = []
        for index, (text, target, strategy, why) in enumerate(CONTROLS, start=1):
            spec = strategy_spec(strategy)
            cases.append(
                AdversarialCase(
                    case_id=case_id_for(strategy, index, control=True),
                    text=text,
                    target_category=target,
                    attack_strategy=strategy,
                    expected_detection=False,
                    metadata={
                        "family": spec.family,
                        "rationale": spec.rationale,
                        "expectation_basis": why,
                        "expectation_note": (
                            "control: guide v2 excludes this category here, so a "
                            "detection is a false positive"
                        ),
                        "expectation_strength": "clear",
                        "statement_source": "author",
                        "certainty_level": "certain",
                    },
                )
            )
        return tuple(cases)


def default_cases() -> tuple[AdversarialCase, ...]:
    """The generated case set the benchmark version is built from."""

    return AdversarialRiskGenerator().generate_all()


def adversarial_records(
    cases: Sequence[AdversarialCase] | None = None,
) -> tuple[dict[str, Any], ...]:
    """Benchmark annotation records for the generated cases."""

    active = cases if cases is not None else default_cases()
    return tuple(case.annotation_record() for case in active)


def attack_counts(cases: Sequence[AdversarialCase]) -> Mapping[str, int]:
    """Attacks per family. Controls are not attacks and are not counted."""

    counts = {family: 0 for family in FAMILIES}
    for case in cases:
        if case.expected_detection:
            counts[case.metadata["family"]] += 1
    return dict(sorted(counts.items()))


def control_counts(cases: Sequence[AdversarialCase]) -> Mapping[str, int]:
    counts = {family: 0 for family in FAMILIES}
    for case in cases:
        if not case.expected_detection:
            counts[case.metadata["family"]] += 1
    return dict(sorted(counts.items()))


def strategy_counts(cases: Sequence[AdversarialCase]) -> Mapping[str, int]:
    counts = {spec.strategy.value: 0 for spec in STRATEGIES}
    for case in cases:
        counts[case.attack_strategy.value] += 1
    return dict(sorted(counts.items()))


def group_counts(cases: Sequence[AdversarialCase]) -> Mapping[str, int]:
    counts = {ATTACK: 0, CONTROL: 0}
    for case in cases:
        counts[case.group] += 1
    return counts


def summarise(cases: Sequence[AdversarialCase]) -> dict[str, Any]:
    """Everything the report needs about the generated set."""

    return {
        "total": len(cases),
        "groups": dict(group_counts(cases)),
        "attacks_by_family": dict(attack_counts(cases)),
        "controls_by_family": dict(control_counts(cases)),
        "by_strategy": dict(strategy_counts(cases)),
        "targets": dict(
            sorted(
                {
                    target: sum(1 for c in cases if c.target_category == target)
                    for target in _taxonomy_categories()
                }.items()
            )
        ),
    }
