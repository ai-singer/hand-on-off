def write(
    analysis: FailureAnalysis,
    metrics: Mapping[str, Any],
    registry_report: Mapping[str, Any],
    generated_payload: Mapping[str, Any],
    summary: Mapping[str, Any],
    *,
    docs_dir: str | Path | None = None,
) -> dict[str, Path]:
    """Write both documents."""

    directory = Path(docs_dir) if docs_dir is not None else DOCS_DIR
    directory.mkdir(parents=True, exist_ok=True)
    dashboard_path = directory / DASHBOARD_NAME
    expansion_path = directory / EXPANSION_NAME
    dashboard_path.write_text(
        dashboard(
            analysis, metrics, registry_report, generated_payload, summary, NOT_FIXED
        ),
        encoding="utf-8",
    )
    expansion_path.write_text(
        expansion_report(
            analysis, metrics, registry_report, generated_payload, summary, NOT_FIXED
        ),
        encoding="utf-8",
    )
    return {DASHBOARD_NAME: dashboard_path, EXPANSION_NAME: expansion_path}
