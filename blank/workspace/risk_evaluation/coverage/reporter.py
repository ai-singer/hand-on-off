"""Reporter: render the coverage dashboard and the expansion report.

Both documents are rendered from the artifacts a run produced, so a number in a
report can always be traced to the record it came from and re-derived by re-running
the pipeline. Nothing here is typed by hand from memory, because a hand-copied metric
is a metric that drifts.

Two documents come out.

`docs/PHASE_R1_COVERAGE_REPORT.md` is the dashboard: current coverage, failure
distribution, the patterns still missing, how the candidates grew, what was not fixed,
and what any evaluator change would have to be measured against.

`docs/PHASE_R1_COVERAGE_EXPANSION_REPORT.md` answers the five questions the phase
poses. Questions 1 to 3 are answered from the measurement. Questions 4 and 5 are
judgements, and they are written as judgements — with the evidence that supports them
and the evidence that would overturn them, rather than as conclusions dressed as
findings.
"""

from __future__ import annotations

from collections import Counter
from pathlib import Path
from typing import Any, Mapping, Sequence

from . import taxonomy
from .model import FailureAnalysis, FailureRecord, GeneratedCase

DOCS_DIR = Path(__file__).resolve().parents[2] / "docs"
DASHBOARD_NAME = "PHASE_R1_COVERAGE_REPORT.md"
EXPANSION_NAME = "PHASE_R1_COVERAGE_EXPANSION_REPORT.md"

#: The status header every phase in this programme carries.
STATUS_HEADER = (
    "**Architecture: PASS / Measurement: PASS / Governance: PASS / "
    "Capability: NEED IMPROVEMENT / Production: NOT READY**"
)

#: The benchmark that would have to exist before anyone may claim an improvement.
REQUIRED_BENCHMARK = (
    "A new independently annotated benchmark, authored after the candidate was "
    "proposed, with its own annotator agreement figures and its own adjudication — "
    "the Phase 8.9 set cannot serve, because it is the set every candidate here was "
    "derived from"
)


def _table(headers: Sequence[str], rows: Sequence[Sequence[object]]) -> str:
    out = ["| " + " | ".join(headers) + " |"]
    out.append("|" + "|".join("---" for _ in headers) + "|")
    for row in rows:
        out.append("| " + " | ".join(str(cell) for cell in row) + " |")
    return "\n".join(out)


def _pct(value: object) -> str:
    try:
        return f"{float(value):.4f}"
    except (TypeError, ValueError):
        return str(value)


def _by(
    records: Sequence[FailureRecord], key
) -> list[tuple[str, int]]:
    counts = Counter(key(record) for record in records)
    return counts.most_common()


def dashboard(
    analysis: FailureAnalysis,
    metrics: Mapping[str, Any],
    registry_report: Mapping[str, Any],
    generated_payload: Mapping[str, Any],
    summary: Mapping[str, Any],
    not_fixed: Sequence[Mapping[str, str]],
) -> str:
    """The coverage dashboard."""

    failures = analysis.failures
    total = len(failures)
    lines: list[str] = [
        "# Phase R1 — Risk Coverage Dashboard",
        "",
        STATUS_HEADER,
        "",
        "This dashboard is generated by `risk_evaluation/coverage/reporter.py` from the",
        "artifacts a pipeline run produced. Every number below exists in",
        "`failure_analysis_r1.json` or the registry, and re-running the pipeline",
        "regenerates this file.",
        "",
        "## 1. Current coverage",
        "",
        f"Source: Phase 8.9 independent benchmark `{metrics.get('benchmark')}` "
        f"version `{metrics.get('benchmark_version')}` — {metrics.get('cases')} cases.",
        "These figures are the frozen evaluator's, read from the phase's own evaluation",
        "module rather than restated. The coverage framework changed none of them.",
        "",
        _table(
            ["metric", "value"],
            [
                ["precision", _pct(metrics.get("precision"))],
                ["recall", _pct(metrics.get("recall"))],
                ["F1", _pct(metrics.get("f1"))],
                ["accuracy", _pct(metrics.get("accuracy"))],
            ],
        ),
        "",
        "## 2. Failure distribution",
        "",
        f"{total} of {analysis.cases} cases fail exact-set match. Distribution over the "
        "nine failure types:",
        "",
        _table(
            ["failure type", "cases", "share", "mean confidence", "auto-generatable"],
            [
                [
                    name,
                    count,
                    f"{count / total:.3f}" if total else "0.000",
                    f"{_mean_confidence(failures, name):.3f}",
                    "yes" if name in taxonomy.AUTO_GENERATABLE else "no",
                ]
                for name, count in analysis.types().items()
            ],
        ),
        "",
        "Outcome shape: "
        + ", ".join(
            f"{name} {count}" for name, count in _by(failures, lambda r: r.outcome)
        )
        + ".",
        "",
        "By language: "
        + ", ".join(f"{name} {count}" for name, count in _by(failures, lambda r: r.language))
        + ". The failure is not language-specific.",
        "",
        "By group: "
        + ", ".join(f"{name} {count}" for name, count in _by(failures, lambda r: r.group))
        + ".",
        "",
        "### Where the failures concentrate",
        "",
        _table(
            ["dimension", "worst", "count"],
            [
                ["form", *_first(_by(failures, lambda r: r.form))],
                ["source_type", *_first(_by(failures, lambda r: r.source_type))],
                ["expected category", *_first(_by(failures, lambda r: r.expected[0] if r.expected else "(none)"))],
            ],
        ),
        "",
        "## 3. Top missing patterns",
        "",
        _table(
            ["rank", "pattern the evaluator lacks", "failure type", "cases"],
            [
                [index, target, failure_type, count]
                for index, ((failure_type, target), count) in enumerate(
                    _top_targets(failures), start=1
                )
            ],
        ),
        "",
        "## 4. Candidate growth",
        "",
        f"{registry_report.get('counts', {}).get('pending', 0)} candidates are in the "
        f"human review queue and {registry_report.get('counts', {}).get('rejected', 0)} "
        "were rejected on provable grounds. Nothing was accepted: acceptance is a human",
        "decision this framework cannot make.",
        "",
        _table(
            ["candidate", "failure type", "category", "covers", "recommendation"],
            [
                [
                    item["candidate_id"],
                    item["failure_type"],
                    item["risk_category"] or "(none)",
                    len(item["covers_cases"]),
                    item["recommendation"],
                ]
                for item in registry_report.get("pending", [])
            ],
        ),
        "",
        f"The expansion generator produced {generated_payload.get('count', 0)} cases from "
        f"{len(generated_payload.get('templates', []))} declared templates. The frozen "
        "evaluator's behaviour on them:",
        "",
        _table(
            ["verdict", "cases"],
            [
                [verdict, count]
                for verdict, count in sorted(generated_payload.get("verdicts", {}).items())
            ],
        ),
        "",
        "## 5. Not fixed",
        "",
        "Recorded here so that a later phase cannot mistake silence for resolution.",
        "",
        _table(
            ["item", "state", "why it is not fixed"],
            [[item["item"], item["state"], item["why"]] for item in not_fixed],
        ),
        "",
        "## 6. Evaluation requirements",
        "",
        "Any change to the evaluator that a candidate proposes must be measured against:",
        "",
        f"1. {REQUIRED_BENCHMARK}.",
        "2. The six registered regression sets, unchanged, with no case removed and no",
        "   label edited.",
        "3. The freeze: `coverage_freeze_r1.json` records the evaluator, benchmark and",
        "   framework digests this run was produced from.",
        "",
        "Until that measurement exists, the only supportable claim about any candidate",
        "is that it addresses an observed failure. No accuracy claim is made here, and",
        "none can be made from this dashboard.",
        "",
    ]
    return "\n".join(lines)


def _mean_confidence(records: Sequence[FailureRecord], failure_type: str) -> float:
    values = [record.confidence for record in records if record.failure_type == failure_type]
    return sum(values) / len(values) if values else 0.0


def _first(pairs: Sequence[tuple[str, int]]) -> tuple[str, int]:
    return pairs[0] if pairs else ("(none)", 0)


def _top_targets(
    records: Sequence[FailureRecord], limit: int = 12
) -> list[tuple[tuple[str, str], int]]:
    counts: Counter[tuple[str, str]] = Counter()
    for record in records:
        repair = record.repair_candidate
        target = repair.target if repair is not None else "human-review"
        counts[(record.failure_type, target)] += 1
    return sorted(counts.items(), key=lambda item: (-item[1], item[0]))[:limit]


def _question_answers(
    analysis: FailureAnalysis,
    metrics: Mapping[str, Any],
    registry_report: Mapping[str, Any],
    generated_payload: Mapping[str, Any],
    summary: Mapping[str, Any],
) -> list[str]:
    failures = analysis.failures
    types = analysis.types()
    total = len(failures) or 1
    auto_cases = summary.get("auto_generatable", 0)
    human_cases = summary.get("human_required", 0)

    biggest = max(types.items(), key=lambda item: item[1]) if types else ("(none)", 0)
    no_relation = [
        item for item in registry_report.get("pending", []) if not item.get("additions")
    ]
    return [
        f"The largest single gap is {biggest[0]} at {biggest[1]} of {total} failures "
        f"({biggest[1] / total:.1%}), followed by "
        + ", ".join(
            f"{name} {count}" for name, count in list(types.items())[1:4]
        )
        + ". Read together with the generator's verdicts, the shape of the gap is "
        "lexical before it is structural: the evaluator's frames are frequently "
        "examined and declined, and the words its lexicons accept are narrower than "
        "the guide's categories.",
        f"{auto_cases} of {total} failures carry a failure type this framework treats as "
        f"auto-generatable ({', '.join(taxonomy.AUTO_GENERATABLE)}), and the generator "
        f"produced {generated_payload.get('count', 0)} cases across "
        f"{len(generated_payload.get('templates', []))} declared templates. "
        "'Auto-generatable' means a candidate can be *built* mechanically from a "
        "declared axis. It does not mean the candidate is correct or that it may be "
        "applied — no candidate from this phase has been applied to anything.",
        f"{human_cases} of {total} failures are typed for human judgement "
        f"({', '.join(taxonomy.HUMAN_REQUIRED)}). Two of the five taxonomy categories — "
        "`unverified_information` and `emotional_manipulation` — have no v3 relation at "
        "all, which the evaluator's own decision layer states outright; for those, a "
        "vocabulary proposal is not merely unwise but unexpressible, and "
        f"{len(no_relation)} candidates in the queue are structural for exactly that "
        "reason.",
        "Not yet, and the order matters. Two conditions are outstanding before touching "
        "the evaluator: a benchmark that did not exist when the candidates were made, "
        "and a decision policy that can absorb a wider lexicon without widening what "
        "counts as a finding. Adding words first would raise recall against the set the "
        "words were derived from, which measures nothing. The framework's own output "
        "argues for patience: most failures are lexical, but the ones that are not "
        "include a structural suppression path that no word list reaches.",
        "All five categories remain barred from production, for three separate reasons. "
        "Precision on the independent set is 0.9062 with recall 0.1758, so the evaluator "
        "is silent on most risk-bearing text. `emotional_manipulation` has no v3 "
        "relation, so its detection rests entirely on a fallback. And every candidate "
        "in this phase is unscored: applying one would change behaviour with no "
        "measurement behind it. Production readiness is not claimable from any artifact "
        "in this phase, and "
        f"the status remains Production: NOT READY.",
    ]


#: Failure classes Phase 8.9 reached with its own classifier, quoted from
#: `docs/PHASE_8_9_INDEPENDENT_VALIDATION_REPORT.md`. Recorded as reference figures so
#: this phase's independent distribution can be compared against them rather than
#: asserted to agree.
PHASE_8_9_REFERENCE: Mapping[str, int] = {
    "lexical_gap": 106,
    "annotation_disagreement": 29,
    "semantic_gap": 8,
    "taxonomy_ambiguity": 4,
    "attribution_error": 4,
}


def _corroboration(
    analysis: FailureAnalysis, metrics: Mapping[str, Any]
) -> list[str]:
    """Where this phase's independent measurement agrees with Phase 8.9's.

    Worth a section of its own because agreement here was not arranged. Phase 8.9
    classified the same 151 failures with a different classifier and a different
    vocabulary; this framework reached its distribution from the evaluator's own
    traces and the declared tables. Two counts landing on the same number is evidence
    that neither is an artifact of its own taxonomy.
    """

    names = Counter(item.name for record in analysis.failures for item in record.evidence)
    types = analysis.types()
    no_hook = names.get("no_hook_at_all", 0)
    false_positives = sum(
        1 for record in analysis.failures if record.outcome == "false_positive"
    )
    annotation_total = types.get(taxonomy.ANNOTATION_CONFLICT, 0) + types.get(
        taxonomy.TAXONOMY_CONFLICT, 0
    )
    confusion = metrics.get("confusion") or {}
    return [
        "## Independent corroboration",
        "",
        "Phase 8.9 classified these same 151 failures with its own classifier. The two",
        "distributions were produced independently — different vocabulary, different",
        "evidence — so the points where they agree are a check on both:",
        "",
        _table(
            ["quantity", "Phase 8.9", "Phase R1", "reading"],
            [
                [
                    "cases whose text names no evaluator lexicon entity",
                    "not measured",
                    no_hook,
                    "Phase 8.9's largest class was lexical_gap at "
                    f"{PHASE_8_9_REFERENCE['lexical_gap']}; this count was reached "
                    "from the lexicon alone and lands on the same number",
                ],
                [
                    "false positives",
                    str(confusion.get("fp", "?")),
                    false_positives,
                    "the evaluator's own metric and this framework's per-case outcome "
                    "agree",
                ],
                [
                    "annotation and taxonomy conflicts",
                    str(
                        PHASE_8_9_REFERENCE["annotation_disagreement"]
                        + PHASE_8_9_REFERENCE["taxonomy_ambiguity"]
                    ),
                    annotation_total,
                    "the split differs because the types differ, but the totals are "
                    "close enough that neither classifier is inventing disagreements",
                ],
                [
                    "exact-set failures",
                    str(sum(PHASE_8_9_REFERENCE.values())),
                    len(analysis.failures),
                    "identical, which is the precondition for the rest to mean anything",
                ],
            ],
        ),
        "",
        "The comparison is not a validation of the candidates. It says the framework",
        "measures the same thing Phase 8.9 measured; it says nothing about whether any",
        "proposed repair would work.",
        "",
    ]


def expansion_report(
    analysis: FailureAnalysis,
    metrics: Mapping[str, Any],
    registry_report: Mapping[str, Any],
    generated_payload: Mapping[str, Any],
    summary: Mapping[str, Any],
    not_fixed: Sequence[Mapping[str, str]],
) -> str:
    """The five-question expansion report."""

    answers = _question_answers(
        analysis, metrics, registry_report, generated_payload, summary
    )
    questions = [
        "What is the largest coverage gap right now?",
        "Which failures can generate a candidate automatically?",
        "Which failures require a human decision?",
        "Is it worth modifying the evaluator in the next phase?",
        "Which risks remain barred from production?",
    ]
    lines: list[str] = [
        "# Phase R1 — Risk Coverage Expansion Report",
        "",
        STATUS_HEADER,
        "",
        "## What this phase did",
        "",
        "Phase R1 built a repeatable Risk Coverage Expansion Framework: a way to run the",
        "frozen evaluator over a labelled set, explain every failure with evidence, turn",
        "the explanations into candidates, and queue those candidates for a human. It did",
        "not modify the evaluator, the taxonomy, the decision policy, any benchmark label,",
        "or any runtime, production, workflow or plugin file. It introduces no LLM, no",
        "network call and no production integration.",
        "",
        "The framework's own numbers below are measurements of the *existing* evaluator,",
        "unchanged:",
        "",
        _table(
            ["metric", "value"],
            [
                ["precision", _pct(metrics.get("precision"))],
                ["recall", _pct(metrics.get("recall"))],
                ["F1", _pct(metrics.get("f1"))],
                ["accuracy", _pct(metrics.get("accuracy"))],
            ],
        ),
        "",
        "## The five questions",
        "",
    ]
    for index, (question, answer) in enumerate(zip(questions, answers), start=1):
        lines.extend([f"### {index}. {question}", "", answer, ""])

    lines.extend(_corroboration(analysis, metrics))

    lines.extend(
        [
            "## Failure distribution, for reference",
            "",
            _table(
                ["failure type", "cases", "mean confidence"],
                [
                    [name, count, f"{_mean_confidence(analysis.failures, name):.3f}"]
                    for name, count in analysis.types().items()
                ],
            ),
            "",
            "## Not fixed",
            "",
            _table(
                ["item", "state", "why it is not fixed"],
                [[item["item"], item["state"], item["why"]] for item in not_fixed],
            ),
            "",
            "## What this phase does not claim",
            "",
            "- It does not claim any accuracy improvement. No evaluator behaviour changed,",
            "  so no metric moved; the framework's contribution is diagnosis.",
            "- It does not claim production readiness, in whole or in part.",
            "- It does not claim that its candidates are correct. They are proposals with",
            "  declared reasoning, addressed to a human.",
            "- It does not claim the failure taxonomy is complete. Unexplained failures are",
            "  reported as UNKNOWN rather than forced into a type.",
            "",
        ]
    )
    return "\n".join(lines)


