BENCHMARK_ID = "risk/independent"
BENCHMARK_VERSION = "v1"
BENCHMARK_DIR = (
    Path(__file__).resolve().parents[1] / "benchmarks" / "risk" / "independent" / "v1"
)

#: The annotation contract, naming both the normative guide and the Phase 8.9
#: protocol that says how the guide was applied. The registry requires every version
#: to name its guide, and a reader of this version needs the protocol too: the labels
#: are two machine annotators' agreement plus adjudication, not one annotator's.
ANNOTATION_PROTOCOL = (
    "docs/RISK_ANNOTATION_GUIDE_v2.md@2.0.0+"
    "docs/INDEPENDENT_ANNOTATION_PROTOCOL_V3.md@3.0.0"
)
ANNOTATION_VERSION = "3.0.0"
CREATED_BY = "creator-agent-framework/phase-8.9"
CREATED_AT = "2026-09-28T05:00:00Z"

