"""The Phase 8.9 dataset as a registered benchmark.

Published at `risk_evaluation/benchmarks/risk/independent/v1/`, beside the other
registered versions, with the four files the registry expects and five more that the
protocol requires:

    cases.json          the adjudicated records, in the registry's shape
    labels.json         the registry's label index
    manifest.json       provenance, prompts, quotas, hashes
    labels_a.json       annotator A's 300 raw labels, untouched
    labels_b.json       annotator B's 300 raw labels, untouched
    disagreements.json  every disagreement, with both reasons
    adjudication.json   every ruling, with its guide citation
    adjudicated.json    the label each case carries and how it was reached

The raw label sets are published for the same reason the freeze records its gate:
a reader who distrusts the adjudication can recompute the benchmark from the pair,
and an agreement figure whose inputs have been overwritten is not evidence.

`source_type` is the frame's, not a guess: the dataset author was told which register
to write in, so the coverage matrix in section 6 of the report crosses a declared
dimension rather than an inferred one.
"""

