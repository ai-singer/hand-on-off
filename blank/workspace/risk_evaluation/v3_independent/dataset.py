class DatasetError(Exception):
    """Raised when the dataset cannot be assembled."""


def evaluate_ready(
    adjudicated: Sequence[AdjudicatedCase],
) -> tuple[AdjudicatedCase, ...]:
    """The cases the primary metrics are computed on: the resolved ones."""

    return tuple(item for item in adjudicated if item.resolved)


def to_record(
    case: GeneratedCase, annotation: Annotation, *, resolved: bool = True
) -> dict[str, Any]:
    """One case in the registry's annotation-record shape."""

    return {
        "id": case.case_id,
        "text": case.text,
        "expected_categories": list(annotation.decision),
        "risk_level": _risk_level(annotation.decision),
        "annotation_reason": annotation.reason,
        "source_type": case.source_type,
        "created_after_evaluator_freeze": True,
        "group": case.group,
        # `resolved` travels with the record so the evaluation stage cannot score a
        # case the adjudicator declined to settle by accident. A flag that lives
        # only in the assembler is a flag the scorer will forget.
        "resolved": resolved,
        "certainty": annotation.certainty,
        "intent": annotation.intent,
        "severity": annotation.severity,
        "speaker": annotation.speaker,
        "stance": annotation.stance,
        "claim": annotation.claim,
        # The frame dimensions travel with the record so section 6's coverage matrix
        # needs no second source and cannot drift from the case it describes.
        "frame": {
            "language": case.language,
            "form": case.form,
            "source_type": case.source_type,
            "topic": case.slot.get("topic", ""),
            "boundary_kind": case.slot.get("boundary_kind", ""),
            "intended_group": case.group,
            "intended_intent": case.slot.get("intent", ""),
        },
    }


#: Severity order, from the taxonomy.
_SEVERITY: Mapping[str, str] = {
    "investment_advice": "block",
    "financial_guarantee": "block",
    "market_prediction": "warning",
    "unverified_information": "warning",
    "emotional_manipulation": "warning",
}


def _risk_level(categories: Sequence[str]) -> str:
    if not categories:
        return "none"
    if any(_SEVERITY.get(name) == "block" for name in categories):
        return "block"
    return "warning"


def build_records(
    cases: Sequence[GeneratedCase], adjudicated: Sequence[AdjudicatedCase]
) -> tuple[dict[str, Any], ...]:
    index = {item.case_id: item for item in adjudicated}
    records: list[dict[str, Any]] = []
    for case in cases:
        entry = index.get(case.case_id)
        if entry is None:
            raise DatasetError(f"{case.case_id}: no adjudicated label")
        records.append(
            to_record(case, entry.annotation, resolved=entry.resolved)
        )
    return tuple(records)


def label_payload(records: Sequence[Mapping[str, Any]]) -> dict[str, Any]:
    by_case = {str(item["id"]): list(item["expected_categories"]) for item in records}
    group_index: dict[str, list[str]] = {}
    category_index: dict[str, list[str]] = {}
    for item in records:
        group_index.setdefault(str(item["group"]), []).append(str(item["id"]))
        for name in item["expected_categories"]:
            category_index.setdefault(str(name), []).append(str(item["id"]))
    return {
        "annotation_version": ANNOTATION_VERSION,
        "case_count": len(records),
        "by_case": by_case,
        "group_index": {
            key: sorted(value) for key, value in sorted(group_index.items())
        },
        "category_index": {
            key: sorted(value) for key, value in sorted(category_index.items())
        },
    }


def achieved_distribution(records: Sequence[Mapping[str, Any]]) -> dict[str, Any]:
    """What the labels actually contain, beside what the frame intended."""

    by_group: dict[str, dict[str, int]] = {}
    categories: dict[str, int] = {}
    for item in records:
        group = str(item["group"])
        bucket = by_group.setdefault(group, {"cases": 0, "with_a_category": 0})
        bucket["cases"] += 1
        if item["expected_categories"]:
            bucket["with_a_category"] += 1
        for name in item["expected_categories"]:
            categories[name] = categories.get(name, 0) + 1
    for bucket in by_group.values():
        bucket["without_a_category"] = bucket["cases"] - bucket["with_a_category"]
    return {
        "by_group": dict(sorted(by_group.items())),
        "by_category": dict(sorted(categories.items())),
        "with_a_category": sum(1 for item in records if item["expected_categories"]),
        "without_a_category": sum(1 for item in records if not item["expected_categories"]),
    }


def manifest(
    records: Sequence[Mapping[str, Any]],
    *,
    adjudicated: Sequence[AdjudicatedCase],
    rulings: Sequence[Ruling],
    agreement: AgreementReport,
) -> dict[str, Any]:
    record = BenchmarkRecord(
        benchmark_id=BENCHMARK_ID,
        version=BENCHMARK_VERSION,
        created_at=CREATED_AT,
        dataset_hash=registry_dataset_hash(records),
        case_count=len(records),
        categories=tuple(
            sorted({name for item in records for name in item["expected_categories"]})
        ),
        annotation_version=ANNOTATION_VERSION,
        annotation_protocol=ANNOTATION_PROTOCOL,
        created_by=CREATED_BY,
        status="frozen",
        group_counts=_group_counts(records),
        source="phase-8.9 machine-generated from a published sampling frame",
    )
    payload = record.as_dict()
    payload.update(
        {
            "provenance": dict(PROVENANCE),
            "frame_quota": quota_summary(),
            "achieved": achieved_distribution(records),
            "agreement": agreement.as_dict(),
            "adjudication": {
                "disputed_cases": sum(1 for item in adjudicated if item.disputed_fields),
                "rulings": len(rulings),
                "resolved_rulings": sum(1 for item in rulings if item.resolved),
                "unresolved_rulings": sum(1 for item in rulings if not item.resolved),
                "resolved_cases": sum(1 for item in adjudicated if item.resolved),
                "unresolved_cases": sum(
                    1 for item in adjudicated if not item.resolved
                ),
                "scored_cases": len(evaluate_ready(adjudicated)),
            },
            "files": {
                "cases": "cases.json",
                "labels": "labels.json",
                "labels_a": "labels_a.json",
                "labels_b": "labels_b.json",
                "disagreements": "disagreements.json",
                "adjudication": "adjudication.json",
                "adjudicated": "adjudicated.json",
            },
            "note": (
                "Synthetic text, machine annotation, two independent annotators and a "
                "third adjudicator. The evaluator was frozen before generation and "
                "was not modified while these numbers were measured. This is not "
                "human inter-annotator agreement and not a real-world accuracy."
            ),
        }
    )
    return payload


def _group_counts(records: Sequence[Mapping[str, Any]]) -> dict[str, int]:
    counts: dict[str, int] = {}
    for item in records:
        group = str(item["group"])
        counts[group] = counts.get(group, 0) + 1
    return dict(sorted(counts.items()))


def write_dataset(
    records: Sequence[Mapping[str, Any]],
    *,
    adjudicated: Sequence[AdjudicatedCase],
    rulings: Sequence[Ruling],
    agreement: AgreementReport,
    labels: Mapping[str, Sequence[Annotation]],
    directory: str | Path | None = None,
) -> Path:
    target = Path(directory) if directory is not None else BENCHMARK_DIR
    target.mkdir(parents=True, exist_ok=True)

    _write(target / "cases.json", [dict(item) for item in records])
    _write(target / "labels.json", label_payload(records))
    _write(
        target / "manifest.json",
        manifest(
            records, adjudicated=adjudicated, rulings=rulings, agreement=agreement
        ),
    )
    for name, items in sorted(labels.items()):
        _write(
            target / f"labels_{name.lower()}.json",
            {
                "annotator": name,
                "case_count": len(items),
                "labels": [item.as_dict() for item in items],
            },
        )
    _write(
        target / "disagreements.json",
        {
            "count": len(agreement.disagreements),
            "affected_cases": len(agreement.affected_cases),
            "disagreements": [item.as_dict() for item in agreement.disagreements],
        },
    )
    _write(
        target / "adjudication.json",
        {
            "rulings": [item.as_dict() for item in rulings],
            "counts": {
                "total": len(rulings),
                "resolved": sum(1 for item in rulings if item.resolved),
                "unresolved": sum(1 for item in rulings if not item.resolved),
            },
        },
    )
    _write(
        target / "adjudicated.json",
        {
            "cases": [item.as_dict() for item in adjudicated],
            "counts": {
                "total": len(adjudicated),
                "resolved": sum(1 for item in adjudicated if item.resolved),
                "unresolved": sum(1 for item in adjudicated if not item.resolved),
            },
        },
    )
    return target


def _write(path: Path, payload: Any) -> None:
    path.write_text(
        json.dumps(payload, indent=2, sort_keys=True, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )


def load_records(directory: str | Path | None = None) -> tuple[dict[str, Any], ...]:
    target = Path(directory) if directory is not None else BENCHMARK_DIR
    return tuple(json.loads((target / "cases.json").read_text(encoding="utf-8")))


def load_manifest(directory: str | Path | None = None) -> dict[str, Any]:
    target = Path(directory) if directory is not None else BENCHMARK_DIR
    return json.loads((target / "manifest.json").read_text(encoding="utf-8"))


def dataset_digest(directory: str | Path | None = None) -> str:
    return registry_dataset_hash(load_records(directory))


def describe() -> dict[str, Any]:
    return {
        "benchmark": f"{BENCHMARK_ID}/{BENCHMARK_VERSION}",
        "directory": str(BENCHMARK_DIR.name),
        "files": sorted(path.name for path in BENCHMARK_DIR.glob("*.json"))
        if BENCHMARK_DIR.is_dir()
        else [],
        "human_annotators": False,
        "synthetic": True,
    }
